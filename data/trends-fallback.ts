import type { Region, Trend, TrendCategory } from "@/types";

/**
 * Curated evergreen-ish internet currents. The roulette falls back to these
 * when every live provider is down, and the Daily Spin draws from the GLOBAL
 * ones only, so every entry has to carry an idea on its own.
 *
 * `angle` is a 3rd-person verb phrase read as "It {angle}." after the pitch,
 * so it describes how the trend shows up *inside a product*, without
 * assuming which product.
 *
 * `score` is an internal roulette weight (35–92), not a popularity claim.
 */

/** Fixed observation time for every curated trend (2026-09-01 UTC). */
export const CURATED_TIMESTAMP = Date.UTC(2026, 8, 1);

interface CuratedSeed {
  slug: string;
  title: string;
  category: TrendCategory;
  score: number;
  heat: "HOT" | "RISING" | "STEADY";
  region: Region;
  tags: string[];
  angle: string;
  nameWords: string[];
}

function curated(seed: CuratedSeed): Trend {
  return {
    id: `curated:${seed.slug}`,
    title: seed.title,
    source: "curated",
    category: seed.category,
    score: seed.score,
    timestamp: CURATED_TIMESTAMP,
    region: seed.region,
    tags: seed.tags,
    sources: ["curated"],
    heat: seed.heat,
    angle: seed.angle,
    nameWords: seed.nameWords,
  };
}

